const fs = require('fs');
const path = require('path');
const authModule = require('../server-auth');

function assert(condition, message) { if (!condition) throw new Error(message); }

const passwordHash = authModule.hashPassword('correct-password', '0123456789abcdef0123456789abcdef');
assert(authModule.verifyPassword('correct-password', passwordHash), 'The correct password should verify');
assert(!authModule.verifyPassword('wrong-password', passwordHash), 'An incorrect password must fail');

const auth = authModule.createAuth({
  sessionSecret: 'test-session-secret',
  accounts: [{
    id: 'teacher-a',
    username: 'TeacherA',
    displayName: 'Teacher A',
    passwordHash,
    classIds: ['class-a']
  }]
});

assert(auth.configured, 'Teacher authentication should report configured accounts');
assert(!auth.login('TeacherA', 'wrong-password', 'test-address').ok, 'Incorrect credentials must be rejected');
const login = auth.login('teachera', 'correct-password', 'test-address');
assert(login.ok && login.token, 'Teacher usernames should be case-insensitive and create a session');

const request = { headers: { cookie: `${authModule.COOKIE_NAME}=${login.token}` } };
const profile = auth.authenticate(request);
assert(profile && profile.id === 'teacher-a', 'A valid session should resolve the teacher');
assert(auth.canAccess(profile, 'class-a'), 'The teacher should access an assigned class');
assert(!auth.canAccess(profile, 'class-b'), 'The teacher must not access an unassigned class');
assert(!Object.prototype.hasOwnProperty.call(profile, 'passwordHash'), 'Public profiles must not expose password hashes');
auth.logout(request);
assert(!auth.authenticate({headers:{}}), 'A cleared browser cookie should end the session');

const restartedAuth = authModule.createAuth({
  sessionSecret: 'test-session-secret',
  accounts: [{
    id: 'teacher-a',
    username: 'TeacherA',
    displayName: 'Teacher A',
    passwordHash,
    classIds: ['class-a']
  }]
});
assert(restartedAuth.authenticate(request), 'Signed teacher sessions should survive a server restart');

const root = path.resolve(__dirname, '..');
const serverSource = fs.readFileSync(path.join(root, 'server.js'), 'utf8');
assert(serverSource.includes('/api/auth/login'), 'The server should expose teacher login');
assert(serverSource.includes('/api/teacher/reviews'), 'Teacher-wide data should use an authenticated endpoint');
assert(serverSource.includes('teacherAuth.canAccess'), 'The server should enforce class assignments');
assert(serverSource.includes('/api/class-roster'), 'The server should expose a protected class roster endpoint');
assert(serverSource.includes('/api/teacher/student-qr'), 'The teacher should generate a protected student QR code');
assert(serverSource.includes('HttpOnly; SameSite=Lax'), 'Student roster access should use an HttpOnly class cookie');

const publicStudents = fs.readFileSync(path.join(root, 'source/shared/students.js'), 'utf8');
const teacherClassroom = fs.readFileSync(path.join(root, 'source/in-class/teacher.html'), 'utf8');
const useClassroom = fs.readFileSync(path.join(root, 'source/in-class/l08-use-pilot.js'), 'utf8');
const studentEntry = fs.readFileSync(path.join(root, 'source/student/entry.html'), 'utf8');
assert(publicStudents.includes('var HSK1_DEFAULT = ["Student"]'), 'Public HSK1 fallback should contain only the test identity');
assert(publicStudents.includes('var HSK3_DEFAULT = ["Student"]'), 'Public HSK3 fallback should contain only the test identity');
assert(!teacherClassroom.includes('api.' + 'qrserver.com'), 'Protected QR codes must be generated by ClassPro, not a third party');
assert(serverSource.includes('if (experiment) payload.experiment = experiment'), 'Protected tickets should preserve the use-classroom experiment');
assert(serverSource.includes('cleanQuery.set("profile", joinPayload.profile)'), 'Student redirects should preserve the use-classroom profile');
assert(useClassroom.includes('experiment: EXPERIMENT') && useClassroom.includes('profile: PROFILE'), 'Use-classroom QR links should identify the teacher MQTT channel');
assert(studentEntry.includes("['experiment', 'profile']"), 'Student name selection should preserve the protected classroom route');

console.log('ClassPro teacher authentication validation passed.');
